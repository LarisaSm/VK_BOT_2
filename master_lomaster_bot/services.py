def format_category_text(key: str) -> str:
    """Формирует текст категории услуг для отправки пользователю."""
    category = SERVICES.get(key)
    if not category:
        return "Раздел не найден."

    lines = [category["title"], "", category["intro"]]
    for index, item in enumerate(category["items"], start=1):
        lines.append(f"{index}. {item['name']} — {item['price']}")
    lines.append("")
    if category.get("note"):
        lines.append(category["note"])
    return "\n".join(lines)
